import { loadSimulationState } from "@/lib/storage/filesystem";
import { DOMAIN_METADATA } from "@/lib/engine/domains";
import type { SimulationState, Domain } from "@/lib/engine/types";

export async function GET(
  request: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params;
  const state = loadSimulationState(id);

  if (!state) {
    return Response.json({ error: "Simulation not found" }, { status: 404 });
  }

  const url = new URL(request.url);
  const format = url.searchParams.get("format") ?? "json";

  if (format === "markdown" || format === "md") {
    const md = buildMarkdown(state);
    return new Response(md, {
      headers: {
        "Content-Type": "text/markdown; charset=utf-8",
        "Content-Disposition": `attachment; filename="counterfact-${id.slice(0, 8)}.md"`,
      },
    });
  }

  // Default: JSON export
  return new Response(JSON.stringify(state, null, 2), {
    headers: {
      "Content-Type": "application/json; charset=utf-8",
      "Content-Disposition": `attachment; filename="counterfact-${id.slice(0, 8)}.json"`,
    },
  });
}

function buildMarkdown(state: SimulationState): string {
  const lines: string[] = [];

  lines.push("# Counterfact Simulation Report");
  lines.push("");
  lines.push("> ⚠ AI-GENERATED SIMULATION — NOT REAL INTELLIGENCE");
  lines.push("");
  lines.push(`**Scenario:** ${state.scenario}`);
  lines.push("");
  if (state.departurePoint) {
    lines.push(`**Departure Point:** ${state.departurePoint}`);
    lines.push("");
  }
  lines.push(`**Created:** ${state.createdAt}`);
  lines.push(`**Prompt Version:** ${state.promptVersion}`);
  lines.push("");

  // Unified Analysis
  if (state.synthesis) {
    lines.push("## Unified Analysis");
    lines.push("");
    lines.push(`**Overall Confidence:** ${state.synthesis.overallConfidence}`);
    lines.push("");
    lines.push(state.synthesis.unifiedAnalysis);
    lines.push("");
  }

  // Domain Reports
  const outputs = Object.entries(state.agentOutputs ?? {});
  if (outputs.length > 0) {
    lines.push("## Domain Reports");
    lines.push("");
    for (const [domain, output] of outputs) {
      const meta = DOMAIN_METADATA[domain as Domain];
      const label = meta ? `${meta.emoji} ${meta.label}` : domain;
      lines.push(`### ${label}`);
      lines.push("");
      lines.push(`**Confidence:** ${output.confidence}`);
      lines.push("");
      lines.push(output.findings);
      lines.push("");
      if (output.keyDatapoints?.length) {
        lines.push("**Key Datapoints:**");
        for (const dp of output.keyDatapoints) {
          lines.push(`- ${dp.fact} *(${dp.source})*`);
        }
        lines.push("");
      }
    }
  }

  // Contradictions
  if (state.synthesis?.contradictions?.length) {
    lines.push("## Contradictions");
    lines.push("");
    for (const c of state.synthesis.contradictions) {
      lines.push(`### ${c.description}`);
      lines.push(`**Mode:** ${c.mode}`);
      lines.push("");
      lines.push(c.resolution);
      lines.push("");
    }
  }

  // Cascade Paths
  if (state.cascades?.scenarioPaths?.length) {
    lines.push("## Scenario Paths");
    lines.push("");
    for (const path of state.cascades.scenarioPaths) {
      lines.push(`### ${path.label} (${path.type})`);
      lines.push("");
      lines.push(path.summary);
      lines.push("");
      if (path.keyMilestones.length) {
        lines.push("| Year | Event | Domain |");
        lines.push("|------|-------|--------|");
        for (const m of path.keyMilestones) {
          lines.push(`| ${m.year} | ${m.event} | ${m.domain} |`);
        }
        lines.push("");
      }
    }
  }

  // Cost
  lines.push("## Cost Summary");
  lines.push("");
  lines.push(`- Input tokens: ${state.costTracking.totalInputTokens.toLocaleString()}`);
  lines.push(`- Output tokens: ${state.costTracking.totalOutputTokens.toLocaleString()}`);
  lines.push(`- Total cost: $${state.costTracking.totalCostUsd.toFixed(4)}`);
  lines.push("");
  lines.push("---");
  lines.push("*Generated by Counterfact Engine*");

  return lines.join("\n");
}
